import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createFileLogger, redact, requestLogging } from '../appLogger.js';
import { EventEmitter } from 'node:events';

test('redacts nested secrets, credential URLs and error causes', () => {
  process.env.TEST_API_KEY = 'private-example-123';
  try {
    const err = new Error('request https://example.test/run?key=private-example-123');
    err.cause = new Error('postgresql://user:password@localhost/db');
    const result = JSON.stringify(redact({ password: 'nope', nested: { apiKey: 'nope' }, err, text: 'private-example-123' }));
    assert(!result.includes('private-example-123'));
    assert(!result.includes('nope'));
    assert(!result.includes('user:password'));
    assert(!result.includes('?key='));
    assert(result.includes('redacted'));
  } finally { delete process.env.TEST_API_KEY; }
});
test('writes JSON lines and bounds rotated log files', () => {
  const directory = mkdtempSync(join(tmpdir(), 'admin-log-'));
  try {
    const log = createFileLogger({ directory, maxBytes: 200, backups: 2 });
    for (let i = 0; i < 12; i++) log('info', 'change', { i, password: 'secret' });
    assert(readdirSync(directory).length <= 3);
    const current = JSON.parse(readFileSync(join(directory, 'app.jsonl'), 'utf8').trim());
    assert.equal(current.details.i, 11);
    assert.equal(current.details.password, '[redacted]');
    assert.equal(current.event, 'change');
  } finally { rmSync(directory, { recursive: true, force: true }); }
});
test('request IDs are generated by the server and staff is recorded at completion', () => {
  const req = { method: 'PUT', path: '/api/students/7' };
  const res = new EventEmitter(); res.statusCode = 200;
  res.setHeader = (k, v) => { assert.equal(k, 'X-Request-ID'); assert.match(v, /^[a-f0-9-]{36}$/); };
  let called = false;
  requestLogging(req, res, () => { called = true; req.staff = { id: 7 }; res.emit('finish'); });
  assert(called);
});
